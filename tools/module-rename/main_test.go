func TestParseFlags(t *testing.T) {
	tests := []struct {
		name    string
		args    []string
		want    options
		wantErr bool
	}{
		{"full", []string{"-from", "a.example/x", "-to", "b.example"}, options{dir: ".", from: "a.example/x", to: "b.example"}, false},
		{"go only with dir", []string{"-dir", "/tmp/w", "-from", "a", "-to", "b", "-go-only"}, options{dir: "/tmp/w", from: "a", to: "b", goOnly: true}, false},
		{"check needs no target", []string{"-check", "-from", "a"}, options{dir: ".", from: "a", check: true}, false},
		{"check with go only", []string{"-check", "-go-only", "-from", "a"}, options{}, true},
		{"missing from", []string{"-to", "b"}, options{}, true},
		{"missing to", []string{"-from", "a"}, options{}, true},
		{"positional argument", []string{"-from", "a", "-to", "b", "extra"}, options{}, true},
		{"unknown flag", []string{"-nope"}, options{}, true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := parseFlags(tt.args)
			if (err != nil) != tt.wantErr {
				t.Fatalf("parseFlags error = %v; wantErr %v", err, tt.wantErr)
			}
			if !tt.wantErr && got != tt.want {
				t.Fatalf("parseFlags = %+v; want %+v", got, tt.want)
			}
		})
	}
}
