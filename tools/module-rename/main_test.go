const (
	goModOld = "module github.com/acme/widget\n\ngo 1.27\n"

	aGoOld = `package a

import (
	"github.com/acme/widget/pkg/b"
	"golang.org/x/z"
)

var _, _ = b.X, z.Y
`

	bGoOld = `// Code generated by fake. DO NOT EDIT.

//go:build linux

package b

import _ "github.com/acme/widget/pkg/a"
`

	badGoOld   = "package bad\n\nimport \"github.com/acme/widget/pkg/b\"\n\nfunc {\n"
	ciYAMLOld  = "flags: -X github.com/acme/widget/pkg/cli.version=1\n"
	changelog  = "Moved from github.com/acme/widget/pkg/old.\n"
	notesOld   = "prefix \"github.com/acme/widget/\"\n"
	binaryData = "\x00github.com/acme/widget/pkg/x\x00"
)

func newRepo(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	files := map[string]string{
		"go.mod":                       goModOld,
		"pkg/a/a.go":                   aGoOld,
		"pkg/b/b.go":                   bGoOld,
		"pkg/bad/bad.go":               badGoOld,
		"ci.yaml":                      ciYAMLOld,
		"CHANGELOG.md":                 changelog,
		"notes.md":                     notesOld,
		"data.bin":                     binaryData,
		"tools/module-rename/skip.txt": "# test skip list\nCHANGELOG.md\n",
	}
	for name, content := range files {
		writeFile(t, filepath.Join(dir, name), content)
	}
	if err := os.Symlink("pkg/a/a.go", filepath.Join(dir, "link.go")); err != nil {
		t.Fatalf("symlink: %v", err)
	}
	for _, args := range [][]string{{"init", "-q"}, {"add", "-A"}} {
		cmd := exec.CommandContext(context.Background(), "git", args...)
		cmd.Dir = dir
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v: %s", args, err, out)
		}
	}
	return dir
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

func readFile(t *testing.T, dir, name string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}
	return string(data)
}

func runTool(t *testing.T, o options) (int, string, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := run(context.Background(), o, &stdout, &stderr)
	return code, stdout.String(), stderr.String()
}

func TestRun(t *testing.T) {
	dir := newRepo(t)
	o := options{dir: dir, from: testFrom, to: testTo}

	code, stdout, stderr := runTool(t, o)
	if code != exitLeftovers {
		t.Fatalf("exit = %d; want %d (stderr %q)", code, exitLeftovers, stderr)
	}
	if want := "notes.md:1: prefix \"github.com/acme/widget/\"\n"; stdout != want {
		t.Fatalf("stdout = %q; want %q", stdout, want)
	}
	if !strings.Contains(stderr, "warning: pkg/bad/bad.go: not formatted") {
		t.Fatalf("stderr %q lacks the formatting warning", stderr)
	}
	if !strings.Contains(stderr, "rewrote 5 occurrences in 5 files") {
		t.Fatalf("stderr %q lacks the expected summary", stderr)
	}

	if got := readFile(t, dir, "go.mod"); got != "module widget.dev\n\ngo 1.27\n" {
		t.Fatalf("go.mod = %q", got)
	}
	a := readFile(t, dir, "pkg/a/a.go")
	if strings.Index(a, `"golang.org/x/z"`) > strings.Index(a, `"widget.dev/pkg/b"`) {
		t.Fatalf("pkg/a/a.go imports not re-sorted:\n%s", a)
	}
	b := readFile(t, dir, "pkg/b/b.go")
	if !strings.HasPrefix(b, "// Code generated by fake. DO NOT EDIT.\n") || !strings.Contains(b, "//go:build linux\n") || !strings.Contains(b, `"widget.dev/pkg/a"`) {
		t.Fatalf("pkg/b/b.go header, build line, or import lost:\n%s", b)
	}
	if got := readFile(t, dir, "pkg/bad/bad.go"); got != strings.Replace(badGoOld, testFrom, testTo, 1) {
		t.Fatalf("pkg/bad/bad.go = %q", got)
	}
	if got := readFile(t, dir, "ci.yaml"); got != "flags: -X widget.dev/pkg/cli.version=1\n" {
		t.Fatalf("ci.yaml = %q", got)
	}
	for name, want := range map[string]string{"CHANGELOG.md": changelog, "data.bin": binaryData} {
		if got := readFile(t, dir, name); got != want {
			t.Fatalf("%s changed to %q", name, got)
		}
	}
	if target, err := os.Readlink(filepath.Join(dir, "link.go")); err != nil || target != "pkg/a/a.go" {
		t.Fatalf("link.go is no longer the original symlink: %q, %v", target, err)
	}

	writeFile(t, filepath.Join(dir, "notes.md"), "prefix \"widget.dev/\"\n")
	code, stdout, stderr = runTool(t, o)
	if code != exitOK || stdout != "" || !strings.Contains(stderr, "rewrote 0 occurrences in 0 files") {
		t.Fatalf("second run: exit %d, stdout %q, stderr %q", code, stdout, stderr)
	}
}

func TestRunCheck(t *testing.T) {
	dir := newRepo(t)
	o := options{dir: dir, from: testFrom, check: true}

	code, stdout, stderr := runTool(t, o)
	if code != exitLeftovers {
		t.Fatalf("exit = %d; want %d (stderr %q)", code, exitLeftovers, stderr)
	}
	var got []string
	for _, line := range strings.Split(strings.TrimSpace(stdout), "\n") {
		path, _, _ := strings.Cut(line, ": ")
		got = append(got, path)
	}
	want := []string{"ci.yaml:1", "go.mod:1", "notes.md:1", "pkg/a/a.go:4", "pkg/b/b.go:7", "pkg/bad/bad.go:3"}
	if strings.Join(got, " ") != strings.Join(want, " ") {
		t.Fatalf("check reported %v; want %v", got, want)
	}
	if !strings.Contains(stderr, "found 6 lines naming github.com/acme/widget") {
		t.Fatalf("stderr %q lacks the expected summary", stderr)
	}
	if got := readFile(t, dir, "go.mod"); got != goModOld {
		t.Fatalf("check mode wrote go.mod: %q", got)
	}

	runTool(t, options{dir: dir, from: testFrom, to: testTo})
	writeFile(t, filepath.Join(dir, "notes.md"), "prefix \"widget.dev/\"\n")
	writeFile(t, filepath.Join(dir, "pkg/bad/bad.go"), "package bad\n")
	if code, stdout, stderr := runTool(t, o); code != exitOK || stdout != "" {
		t.Fatalf("check on a renamed tree: exit %d, stdout %q, stderr %q", code, stdout, stderr)
	}
}

func TestRunLeavesSymlinkTargetOutsideCheckout(t *testing.T) {
	dir := newRepo(t)
	outside := filepath.Join(t.TempDir(), "outside.go")
	writeFile(t, outside, aGoOld)
	if err := os.Symlink(outside, filepath.Join(dir, "escape.go")); err != nil {
		t.Fatalf("symlink: %v", err)
	}
	cmd := exec.CommandContext(context.Background(), "git", "add", "escape.go")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git add: %v: %s", err, out)
	}
	runTool(t, options{dir: dir, from: testFrom, to: testTo})
	if got := readFile(t, filepath.Dir(outside), filepath.Base(outside)); got != aGoOld {
		t.Fatalf("file behind a tracked symlink was rewritten: %q", got)
	}
}

func TestRunPreservesNonCanonicalGoFiles(t *testing.T) {
	dir := newRepo(t)
	files := map[string]string{
		"pkg/crlf/crlf.go":   "package crlf\r\n\r\nimport _ \"github.com/acme/widget/pkg/b\"\r\n",
		"pkg/messy/messy.go": "package messy\n\nimport _ \"github.com/acme/widget/pkg/b\"\n\nvar   x=1\n",
		"pkg/nonl/nonl.go":   "package nonl\n\nimport _ \"github.com/acme/widget/pkg/b\"",
	}
	for name, content := range files {
		writeFile(t, filepath.Join(dir, name), content)
	}
	cmd := exec.CommandContext(context.Background(), "git", "add", "-A")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git add: %v: %s", err, out)
	}
	_, _, stderr := runTool(t, options{dir: dir, from: testFrom, to: testTo})
	for name, content := range files {
		if got, want := readFile(t, dir, name), strings.Replace(content, testFrom, testTo, 1); got != want {
			t.Errorf("%s = %q; want only the path swapped: %q", name, got, want)
		}
		if !strings.Contains(stderr, "warning: "+name+": not formatted") {
			t.Errorf("stderr %q lacks a warning for %s", stderr, name)
		}
	}
}

func TestRunGoOnly(t *testing.T) {
	dir := newRepo(t)
	code, stdout, stderr := runTool(t, options{dir: dir, from: testFrom, to: testTo, goOnly: true})
	if code != exitOK || stdout != "" {
		t.Fatalf("exit %d, stdout %q, stderr %q", code, stdout, stderr)
	}
	if got := readFile(t, dir, "ci.yaml"); got != ciYAMLOld {
		t.Fatalf("ci.yaml rewritten in go-only mode: %q", got)
	}
	if got := readFile(t, dir, "go.mod"); got != "module widget.dev\n\ngo 1.27\n" {
		t.Fatalf("go.mod = %q", got)
	}
}

func TestRunErrors(t *testing.T) {
	dir := newRepo(t)
	tests := []struct {
		name string
		o    options
	}{
		{"same paths", options{dir: dir, from: testFrom, to: testFrom}},
		{"not a git checkout", options{dir: t.TempDir(), from: testFrom, to: testTo}},
		{"missing explicit skip list", options{dir: dir, from: testFrom, to: testTo, skip: filepath.Join(dir, "absent.txt")}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if code, _, stderr := runTool(t, tt.o); code != exitError || stderr == "" {
				t.Fatalf("exit %d, stderr %q; want %d with a message", code, stderr, exitError)
			}
		})
	}
}

