// values_test.go tests reading back the merged Helm values a bundle installed.
//
// Area of Concern: recovering what a bundle actually deployed
// - ReadReleaseValues() - per-deployer layout, layering, and fail-closed reads
//
// The layouts are not hypothetical: five deployers write <path>/values.yaml
// with cluster-values.yaml layered on top, flux inlines the same values under
// spec.values in its HelmRelease, and fleet's HelmOp mode under
// spec.helm.values in a shared helmops.yaml.

