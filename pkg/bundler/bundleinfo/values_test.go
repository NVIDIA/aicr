// valuesBundle writes a minimal but valid bundle-info.yaml naming the given
// releases, so each case exercises Read's own validation rather than routing
// around it.
func valuesBundle(t *testing.T, releases []bundleinfo.Release) string {
	t.Helper()
	return valuesBundleWith(t, releases, false)
}

func valuesBundleWith(t *testing.T, releases []bundleinfo.Release, vendored bool) string {
	t.Helper()
	dir := t.TempDir()
	info := &bundleinfo.BundleInfo{
		APIVersion: header.StableGroupVersion,
		Kind:       string(header.KindBundleInfo),
		Build: bundleinfo.Build{
			Deployer: "helm",
			Recipe: bundleinfo.Recipe{
				Path:   "recipe.yaml",
				Digest: "sha256:3b1f8c2ad9e7546102bb8f4c7d0e9a1358cc4f6b2e8d70a94f1c5b3e6d820947",
			},
			Settings: bundleinfo.Settings{VendorCharts: vendored},
		},
		Layout: bundleinfo.Layout{Entrypoint: "deploy.sh", Releases: releases},
	}
	if _, err := bundleinfo.Write(context.Background(), dir, info); err != nil {
		t.Fatalf("Write() failed: %v", err)
	}
	return dir
}

// plant writes content at dir/rel, creating parents.
func plant(t *testing.T, dir, rel, content string) {
	t.Helper()
	path := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatalf("MkdirAll(%s) failed: %v", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatalf("WriteFile(%s) failed: %v", path, err)
	}
}

func TestReadReleaseValues(t *testing.T) {
	tests := []struct {
		name     string
		releases []bundleinfo.Release
		files    map[string]string
		want     map[string]map[string]any
	}{
		{
			name: "values.yaml alone",
			releases: []bundleinfo.Release{
				{Name: "nodewright-operator", Component: "nodewright-operator", Path: "005-nodewright-operator"},
			},
			files: map[string]string{
				"005-nodewright-operator/values.yaml": "fullnameOverride: skyhook-operator\n",
			},
			want: map[string]map[string]any{
				"nodewright-operator": {"fullnameOverride": "skyhook-operator"},
			},
		},
		{
			name: "cluster-values.yaml layers over values.yaml",
			releases: []bundleinfo.Release{
				{Name: "c", Component: "c", Path: "001-c"},
			},
			files: map[string]string{
				"001-c/values.yaml":         "fullnameOverride: from-values\nkeep: true\n",
				"001-c/cluster-values.yaml": "fullnameOverride: from-cluster\n",
			},
			want: map[string]map[string]any{
				"c": {"fullnameOverride": "from-cluster", "keep": true},
			},
		},
		{
			name: "an empty cluster-values.yaml changes nothing",
			releases: []bundleinfo.Release{
				{Name: "c", Component: "c", Path: "001-c"},
			},
			files: map[string]string{
				"001-c/values.yaml":         "fullnameOverride: kept\n",
				"001-c/cluster-values.yaml": "# Generated by AICR\n---\n",
			},
			want: map[string]map[string]any{"c": {"fullnameOverride": "kept"}},
		},
		{
			name: "cluster-values.yaml deep-merges rather than replacing",
			releases: []bundleinfo.Release{
				{Name: "c", Component: "c", Path: "001-c"},
			},
			files: map[string]string{
				"001-c/values.yaml":         "grafana:\n  fullnameOverride: g\n  other: keep\n",
				"001-c/cluster-values.yaml": "grafana:\n  fullnameOverride: g2\n",
			},
			want: map[string]map[string]any{
				"c": {"grafana": map[string]any{"fullnameOverride": "g2", "other": "keep"}},
			},
		},
		{
			name: "flux reads spec.values from the recorded manifest",
			releases: []bundleinfo.Release{
				{
					Name:      "nodewright-operator",
					Component: "nodewright-operator",
					Path:      "nodewright-operator",
					Manifest:  "nodewright-operator/helmrelease.yaml",
				},
			},
			files: map[string]string{
				"nodewright-operator/helmrelease.yaml": "apiVersion: helm.toolkit.fluxcd.io/v2\n" +
					"kind: HelmRelease\n" +
					"metadata:\n  name: nodewright-operator\n" +
					"spec:\n  values:\n    fullnameOverride: skyhook-operator\n",
			},
			want: map[string]map[string]any{
				"nodewright-operator": {"fullnameOverride": "skyhook-operator"},
			},
		},
		{
			name: "values.yaml wins over a manifest that also carries values",
			releases: []bundleinfo.Release{
				{Name: "c", Component: "c", Path: "001-c", Manifest: "001-c/application.yaml"},
			},
			files: map[string]string{
				"001-c/values.yaml": "fullnameOverride: from-values-file\n",
				"001-c/application.yaml": "apiVersion: argoproj.io/v1alpha1\nkind: Application\n" +
					"spec:\n  values:\n    fullnameOverride: should-not-win\n",
			},
			want: map[string]map[string]any{"c": {"fullnameOverride": "from-values-file"}},
		},
		{
			// Fleet installs the values inlined in each HelmOp and never reads
			// the folder files, so a user's edit to helmops.yaml must be what
			// is read back, not the stale values.yaml beside it.
			name: "a fleet HelmOp is read from the shared manifest, not the folder files",
			releases: []bundleinfo.Release{
				{Name: "a", Component: "a", Path: "001-a", Manifest: "helmops.yaml"},
				{Name: "b", Component: "b", Path: "002-b", Manifest: "helmops.yaml"},
			},
			files: map[string]string{
				"001-a/values.yaml":         "fullnameOverride: stale-a\n",
				"001-a/cluster-values.yaml": "fullnameOverride: stale-cluster-a\n",
				"002-b/values.yaml":         "fullnameOverride: stale-b\n",
				"helmops.yaml": "# Generated by AICR\n" +
					"apiVersion: fleet.cattle.io/v1alpha1\nkind: HelmOp\n" +
					"metadata:\n  name: aicr-a\n" +
					"spec:\n  helm:\n    releaseName: a\n    values:\n      fullnameOverride: edited-a\n" +
					"---\n" +
					"apiVersion: fleet.cattle.io/v1alpha1\nkind: HelmOp\n" +
					"metadata:\n  name: aicr-b\n" +
					"spec:\n  helm:\n    releaseName: b\n    values:\n      fullnameOverride: edited-b\n",
			},
			want: map[string]map[string]any{
				"a": {"fullnameOverride": "edited-a"},
				"b": {"fullnameOverride": "edited-b"},
			},
		},
		{
			name: "a HelmOp without spec.helm.values states an empty set",
			releases: []bundleinfo.Release{
				{Name: "a", Component: "a", Path: "001-a", Manifest: "helmops.yaml"},
			},
			files: map[string]string{
				"001-a/values.yaml": "fullnameOverride: stale-a\n",
				"helmops.yaml": "apiVersion: fleet.cattle.io/v1alpha1\nkind: HelmOp\n" +
					"spec:\n  helm:\n    releaseName: a\n    chart: a\n",
			},
			want: map[string]map[string]any{"a": {}},
		},
		{
			// Present with an empty map, not absent: the manifest exists and
			// declares no values, which is a statement that the release pinned
			// none. See TestReadReleaseValuesKeepsAReleaseThatPinnedNothing.
			name: "a manifest without spec.values states an empty set",
			releases: []bundleinfo.Release{
				{Name: "c", Component: "c", Path: "001-c", Manifest: "001-c/helmrelease.yaml"},
			},
			files: map[string]string{
				"001-c/helmrelease.yaml": "apiVersion: helm.toolkit.fluxcd.io/v2\nkind: HelmRelease\n" +
					"spec:\n  chart:\n    spec:\n      chart: nodewright\n",
			},
			want: map[string]map[string]any{"c": {}},
		},
		{
			name:     "a bundle with no releases yields nothing",
			releases: nil,
			files:    nil,
			want:     map[string]map[string]any{},
		},
		{
			name: "releases are keyed by component, not by release name",
			releases: []bundleinfo.Release{
				{Name: "aicr-stack-c", Component: "c", Path: "001-c"},
			},
			files: map[string]string{"001-c/values.yaml": "fullnameOverride: x\n"},
			want:  map[string]map[string]any{"c": {"fullnameOverride": "x"}},
		},
		{
			// An injected wrapper carries its PARENT in Component, so counting
			// its values would attribute them to a chart that never saw them —
			// and here it would beat the real release to the key, since -pre
			// lands at the earlier wave.
			name: "an injected -pre release does not shadow its component",
			releases: []bundleinfo.Release{
				{Name: "c-pre", Component: "c", Path: "001-c-pre"},
				{Name: "c", Component: "c", Path: "002-c"},
			},
			files: map[string]string{
				"001-c-pre/values.yaml": "fullnameOverride: wrapper\n",
				"002-c/values.yaml":     "fullnameOverride: real\n",
			},
			want: map[string]map[string]any{"c": {"fullnameOverride": "real"}},
		},
		{
			name: "a component whose own name ends in a reserved suffix is kept",
			releases: []bundleinfo.Release{
				{Name: "thing-post", Component: "thing-post", Path: "001-thing-post"},
			},
			files: map[string]string{"001-thing-post/values.yaml": "fullnameOverride: kept\n"},
			want:  map[string]map[string]any{"thing-post": {"fullnameOverride": "kept"}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := valuesBundle(t, tt.releases)
			for rel, content := range tt.files {
				plant(t, dir, rel, content)
			}
			got, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
			if err != nil {
				t.Fatalf("ReadReleaseValues() failed: %v", err)
			}
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("ReadReleaseValues() = %#v, want %#v", got, tt.want)
			}
		})
	}
}

// TestReadReleaseValuesPropagatesMissingBundleInfo keeps the pre-stamping
// bundle a real state a caller can branch on, rather than an empty result that
// reads as "this bundle pinned no object names".
func TestReadReleaseValuesPropagatesMissingBundleInfo(t *testing.T) {
	_, err := bundleinfo.ReadReleaseValues(context.Background(), t.TempDir())
	if err == nil {
		t.Fatal("want an error for a directory with no bundle-info.yaml, got nil")
	}
	if errorstest.ReportedCode(err) != errors.ErrCodeNotFound {
		t.Errorf("want ErrCodeNotFound, got %v", err)
	}
}

// TestReadReleaseValuesRefusesSymlink mirrors Read's own O_NOFOLLOW guard: an
// untrusted bundle arrives from an OCI registry or a GitOps clone and must not
// redirect this read at anything outside itself.
func TestReadReleaseValuesRefusesSymlink(t *testing.T) {
	dir := valuesBundle(t, []bundleinfo.Release{
		{Name: "c", Component: "c", Path: "001-c"},
	})
	outside := filepath.Join(t.TempDir(), "elsewhere.yaml")
	if err := os.WriteFile(outside, []byte("fullnameOverride: leaked\n"), 0o600); err != nil {
		t.Fatalf("WriteFile() failed: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "001-c"), 0o750); err != nil {
		t.Fatalf("MkdirAll() failed: %v", err)
	}
	if err := os.Symlink(outside, filepath.Join(dir, "001-c", "values.yaml")); err != nil {
		t.Fatalf("Symlink() failed: %v", err)
	}

	_, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
	if err == nil {
		t.Fatal("want a symlinked values.yaml refused, got nil")
	}
	if !strings.Contains(err.Error(), "symlink") {
		t.Errorf("want the error to name the symlink, got %v", err)
	}
}

// TestReadReleaseValuesRejectsOversizeValues bounds the read the same way
// Read bounds its own: a values file is attacker-influenced input.
func TestReadReleaseValuesRejectsOversizeValues(t *testing.T) {
	dir := valuesBundle(t, []bundleinfo.Release{
		{Name: "c", Component: "c", Path: "001-c"},
	})
	plant(t, dir, "001-c/values.yaml",
		"key: "+strings.Repeat("x", int(defaults.MaxBundleValuesBytes))+"\n")

	_, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
	if err == nil {
		t.Fatal("want an oversize values.yaml rejected, got nil")
	}
	if errorstest.ReportedCode(err) != errors.ErrCodeInvalidRequest {
		t.Errorf("want ErrCodeInvalidRequest, got %v", err)
	}
}

// A --vendor-charts bundle nests its values one level under the vendored
// chart's name, because that is the only way Helm forwards a wrapper's values
// to a subchart. Read verbatim, every object-name path would be one level too
// deep, so a comparison against a resolved recipe would report the real name
// as dropped and a phantom nested one as added — and --inherit-from would act
// on that by nulling out the name it exists to preserve.
func TestReadReleaseValuesUnnestsVendoredCharts(t *testing.T) {
	const wrapperChart = "apiVersion: v2\nname: gpu-operator\nversion: 0.1.0\n" +
		"dependencies:\n  - name: gpu-operator\n    version: v25.3.4\n    repository: \"\"\n"

	tests := []struct {
		name     string
		vendored bool
		manifest string // set for a flux-layout release
		files    map[string]string
		want     map[string]any
	}{
		{
			// Flux stores values in the HelmRelease, nested under the subchart
			// key exactly as the other deployers nest values.yaml. Read flat,
			// inheritance saw the real name as dropped and null-pinned it.
			name:     "a vendored flux release is un-nested from spec.values",
			vendored: true,
			manifest: "001-c/helmrelease.yaml",
			files: map[string]string{
				"001-c/Chart.yaml": wrapperChart,
				"001-c/helmrelease.yaml": "apiVersion: helm.toolkit.fluxcd.io/v2\nkind: HelmRelease\n" +
					"spec:\n  values:\n    gpu-operator:\n      fullnameOverride: gpu-operator\n",
			},
			want: map[string]any{"fullnameOverride": "gpu-operator"},
		},
		{
			// nestUnderSubchart emits no key at all for empty values, so there
			// is nothing to strip.
			name:     "a vendored release with empty values stays empty",
			vendored: true,
			files: map[string]string{
				"001-c/Chart.yaml":  wrapperChart,
				"001-c/values.yaml": "# Generated by AICR\n---\n",
			},
			want: map[string]any{},
		},
		{
			name:     "a vendored bundle release without a wrapper chart is left flat",
			vendored: true,
			files:    map[string]string{"001-c/values.yaml": "fullnameOverride: flat\n"},
			want:     map[string]any{"fullnameOverride": "flat"},
		},
		{
			name:     "a vendored release is read at the subchart's depth",
			vendored: true,
			files: map[string]string{
				"001-c/Chart.yaml":  wrapperChart,
				"001-c/values.yaml": "gpu-operator:\n  fullnameOverride: gpu-operator\n",
			},
			want: map[string]any{"fullnameOverride": "gpu-operator"},
		},
		{
			// The chart name is not always the component name, so the key is
			// taken from the wrapper's dependency rather than guessed.
			name:     "the subchart key comes from the wrapper dependency",
			vendored: true,
			files: map[string]string{
				"001-c/Chart.yaml": "apiVersion: v2\nname: c\nversion: 0.1.0\n" +
					"dependencies:\n  - name: not-the-component-name\n    version: v1\n    repository: \"\"\n",
				"001-c/values.yaml": "not-the-component-name:\n  fullnameOverride: real\n",
			},
			want: map[string]any{"fullnameOverride": "real"},
		},
		{
			name:     "cluster-values layers before the un-nesting",
			vendored: true,
			files: map[string]string{
				"001-c/Chart.yaml":  wrapperChart,
				"001-c/values.yaml": "gpu-operator:\n  fullnameOverride: from-values\n",
				"001-c/cluster-values.yaml": "gpu-operator:\n" +
					"  fullnameOverride: from-cluster\n",
			},
			want: map[string]any{"fullnameOverride": "from-cluster"},
		},
		{
			// An injected local-helm folder carries no dependency, so there is
			// nothing nested and its values must be left alone.
			name:     "a wrapper with no dependency is left flat",
			vendored: true,
			files: map[string]string{
				"001-c/Chart.yaml":  "apiVersion: v2\nname: c\nversion: 0.1.0\n",
				"001-c/values.yaml": "fullnameOverride: flat\n",
			},
			want: map[string]any{"fullnameOverride": "flat"},
		},
		{
			name:     "a non-vendored bundle is never un-nested",
			vendored: false,
			files: map[string]string{
				"001-c/Chart.yaml":  wrapperChart,
				"001-c/values.yaml": "gpu-operator:\n  fullnameOverride: gpu-operator\n",
			},
			want: map[string]any{"gpu-operator": map[string]any{"fullnameOverride": "gpu-operator"}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := valuesBundleWith(t, []bundleinfo.Release{
				{Name: "c", Component: "c", Path: "001-c", Manifest: tt.manifest},
			}, tt.vendored)
			for rel, content := range tt.files {
				plant(t, dir, rel, content)
			}
			got, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
			if err != nil {
				t.Fatalf("ReadReleaseValues() failed: %v", err)
			}
			if !reflect.DeepEqual(got["c"], tt.want) {
				t.Errorf("values = %#v, want %#v", got["c"], tt.want)
			}
		})
	}
}

// A component whose values file is comments-only (grove ships one) states an
// empty map, which is a fact: it deployed and pinned nothing. Dropping it
// would tell inheritance this is a first deploy, so a name a later release
// adds would apply instead of being held back — while upgrade-check, reading
// the same two artifacts, would report the rename. The two halves must agree.
func TestReadReleaseValuesKeepsAReleaseThatPinnedNothing(t *testing.T) {
	tests := []struct {
		name      string
		release   bundleinfo.Release
		files     map[string]string
		wantEntry bool
	}{
		{
			name:      "a comments-only values file is an empty statement, not an absence",
			release:   bundleinfo.Release{Name: "c", Component: "c", Path: "001-c"},
			files:     map[string]string{"001-c/values.yaml": "# Generated by AICR\n---\n"},
			wantEntry: true,
		},
		{
			name:    "a manifest declaring no values is also a statement",
			release: bundleinfo.Release{Name: "c", Component: "c", Path: "001-c", Manifest: "001-c/hr.yaml"},
			files: map[string]string{
				"001-c/hr.yaml": "apiVersion: helm.toolkit.fluxcd.io/v2\nkind: HelmRelease\nspec:\n  chart: {}\n",
			},
			wantEntry: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := valuesBundle(t, []bundleinfo.Release{tt.release})
			for rel, content := range tt.files {
				plant(t, dir, rel, content)
			}
			got, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
			if err != nil {
				t.Fatalf("ReadReleaseValues() failed: %v", err)
			}
			values, present := got["c"]
			if present != tt.wantEntry {
				t.Fatalf("entry present = %v, want %v (values %#v)", present, tt.wantEntry, values)
			}
			if tt.wantEntry && len(values) != 0 {
				t.Errorf("values = %#v, want an empty map", values)
			}
		})
	}
}

// An incompletely copied bundle must be rejected, not read as a release that
// pinned nothing. "Pinned nothing" is a statement inheritance acts on: with a
// current fullnameOverride and an empty prior, it writes a null that deletes
// the deployed name and renames every object the release owns.
func TestReadReleaseValuesRejectsIncompleteBundle(t *testing.T) {
	tests := []struct {
		name    string
		release bundleinfo.Release
		files   map[string]string
		wantMsg string
	}{
		{
			name: "a recorded flux manifest that is missing",
			release: bundleinfo.Release{
				Name: "c", Component: "c", Path: "c", Manifest: "c/helmrelease.yaml",
			},
			files:   nil,
			wantMsg: "c/helmrelease.yaml",
		},
		{
			// The folder's values.yaml is not what Fleet installed, so falling
			// back to it would read stale values as the deployed ones.
			name: "a HelmOp manifest with no HelmOp for the release",
			release: bundleinfo.Release{
				Name: "c", Component: "c", Path: "001-c", Manifest: "helmops.yaml",
			},
			files: map[string]string{
				"001-c/values.yaml": "fullnameOverride: stale\n",
				"helmops.yaml": "apiVersion: fleet.cattle.io/v1alpha1\nkind: HelmOp\n" +
					"spec:\n  helm:\n    releaseName: other\n",
			},
			wantMsg: `no HelmOp for release "c"`,
		},
		{
			// Every local-format folder writes values.yaml unconditionally,
			// so a release with neither it nor a manifest was truncated.
			name:    "neither values.yaml nor a manifest",
			release: bundleinfo.Release{Name: "c", Component: "c", Path: "001-c"},
			files:   map[string]string{"001-c/install.sh": "#!/bin/sh\n"},
			wantMsg: "incomplete",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := valuesBundle(t, []bundleinfo.Release{tt.release})
			for rel, content := range tt.files {
				plant(t, dir, rel, content)
			}
			got, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
			if err == nil {
				t.Fatalf("want an incomplete bundle rejected, got values %#v", got)
			}
			if errorstest.ReportedCode(err) != errors.ErrCodeInvalidRequest {
				t.Errorf("want ErrCodeInvalidRequest, got %v", err)
			}
			// NotFound is reserved for a bundle predating bundle-info.yaml,
			// which callers treat as a skippable state rather than a fault.
			if stderrors.Is(err, errors.New(errors.ErrCodeNotFound, "")) {
				t.Errorf("an incomplete bundle must not read as a pre-stamping one: %v", err)
			}
			if !strings.Contains(err.Error(), tt.wantMsg) {
				t.Errorf("error %q does not mention %q", err.Error(), tt.wantMsg)
			}
		})
	}
}

// A flux HelmRelease built with --dynamic takes those paths through
// spec.valuesFrom, so spec.values is only part of what it installed with. That
// is ErrCodeUnavailable rather than InvalidRequest: the bundle is well-formed,
// and callers treat the two differently — inheritance warns on the first and
// refuses the artifact on the second.
func TestReadReleaseValuesWithholdsAReleaseWithValuesFrom(t *testing.T) {
	dir := valuesBundle(t, []bundleinfo.Release{
		{Name: "c", Component: "c", Path: "c", Manifest: "c/helmrelease.yaml"},
	})
	plant(t, dir, "c/helmrelease.yaml", "apiVersion: helm.toolkit.fluxcd.io/v2\nkind: HelmRelease\n"+
		"spec:\n  values:\n    other: kept\n  valuesFrom:\n    - kind: ConfigMap\n      name: c-dynamic\n")

	got, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
	if err == nil {
		t.Fatalf("want a release with valuesFrom withheld, got values %#v", got)
	}
	if errorstest.ReportedCode(err) != errors.ErrCodeUnavailable {
		t.Errorf("want ErrCodeUnavailable, got %v", err)
	}
	if stderrors.Is(err, errors.New(errors.ErrCodeInvalidRequest, "")) {
		t.Errorf("a well-formed bundle must not read as an incomplete one: %v", err)
	}
	if !strings.Contains(err.Error(), "valuesFrom") {
		t.Errorf("error %q does not name valuesFrom", err.Error())
	}
}

// O_NOFOLLOW guards only the final path component, so a release directory that
// is itself a symlink — preserved by both git and OCI — would redirect the read
// outside the bundle. The leaf-file case is TestReadReleaseValuesRefusesSymlink.
func TestReadReleaseValuesRefusesSymlinkedReleaseDirectory(t *testing.T) {
	dir := valuesBundle(t, []bundleinfo.Release{{Name: "c", Component: "c", Path: "001-c"}})
	outside := t.TempDir()
	if err := os.WriteFile(filepath.Join(outside, "values.yaml"),
		[]byte("fullnameOverride: from-outside-bundle\n"), 0o600); err != nil {
		t.Fatalf("setup: write: %v", err)
	}
	if err := os.Symlink(outside, filepath.Join(dir, "001-c")); err != nil {
		t.Fatalf("setup: symlink: %v", err)
	}

	got, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
	if err == nil {
		t.Fatalf("want a symlinked release directory refused, got values %#v", got)
	}
	if errorstest.ReportedCode(err) != errors.ErrCodeInvalidRequest {
		t.Errorf("want ErrCodeInvalidRequest, got %v", err)
	}
	if !strings.Contains(err.Error(), "directory symlink") {
		t.Errorf("error %q does not name the directory symlink", err.Error())
	}
}

