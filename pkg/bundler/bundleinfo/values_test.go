// TestReadReleaseValuesRejectsMalformedYAML keeps a values file that does not
// parse an error rather than an empty projection. Silently reading no object
// names out of an unreadable file would report that a component pins none,
// which is the false "nothing moved" this axis exists to remove.
func TestReadReleaseValuesRejectsMalformedYAML(t *testing.T) {
	tests := []struct {
		name     string
		releases []bundleinfo.Release
		files    map[string]string
	}{
		{
			name:     "values.yaml",
			releases: []bundleinfo.Release{{Name: "c", Component: "c", Path: "001-c"}},
			files:    map[string]string{"001-c/values.yaml": "fullnameOverride: [unclosed\n"},
		},
		{
			name:     "cluster-values.yaml",
			releases: []bundleinfo.Release{{Name: "c", Component: "c", Path: "001-c"}},
			files: map[string]string{
				"001-c/values.yaml":         "fullnameOverride: fine\n",
				"001-c/cluster-values.yaml": "\tthis: is not yaml\n",
			},
		},
		{
			name: "flux manifest",
			releases: []bundleinfo.Release{
				{Name: "c", Component: "c", Path: "001-c", Manifest: "001-c/helmrelease.yaml"},
			},
			files: map[string]string{"001-c/helmrelease.yaml": "spec:\n  values: [unclosed\n"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := valuesBundle(t, tt.releases)
			for rel, content := range tt.files {
				plant(t, dir, rel, content)
			}
			_, err := bundleinfo.ReadReleaseValues(context.Background(), dir)
			if err == nil {
				t.Fatal("want malformed YAML rejected, got nil")
			}
			if errorstest.ReportedCode(err) != errors.ErrCodeInvalidRequest {
				t.Errorf("want ErrCodeInvalidRequest, got %v", err)
			}
		})
	}
}

// TestReadReleaseValuesRejectsIrregularFile mirrors Read's regular-file check.
