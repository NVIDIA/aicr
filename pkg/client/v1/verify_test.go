// TestValidateIdentityPattern mirrors the guard the verify entry points apply
// internally, so callers can pre-validate operator input.
func TestValidateIdentityPattern(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		pattern string
		wantErr bool
	}{
		{name: "trusted default", pattern: aicr.TrustedIdentityPattern},
		{
			name:    "retargeted NVIDIA workflow",
			pattern: `^https://github\.com/NVIDIA/aicr/\.github/workflows/server-kms-e2e\.yaml@.*`,
		},
		{name: "other repository", pattern: `^https://github\.com/evil/repo/.*`, wantErr: true},
		{name: "empty", pattern: "", wantErr: true},
		{name: "match anything", pattern: `.*`, wantErr: true},

		// Widening bypasses. Each carries the required repository prefix, so a
		// substring anchor alone lets them through, but each admits identities
		// outside NVIDIA/aicr — reducing the gate to the OIDC issuer pin, which
		// any GitHub Actions workflow in any repository satisfies.
		{
			name:    "trailing alternation matches anything",
			pattern: `^https://github\.com/NVIDIA/aicr/.*|.*$`,
			wantErr: true,
		},
		{
			name:    "leading alternation matches anything",
			pattern: `.*|https://github.com/NVIDIA/aicr/.*`,
			wantErr: true,
		},
		{
			name:    "alternation to one foreign repository",
			pattern: `https://github.com/NVIDIA/aicr/.*|^https://github\.com/evil/repo/.*`,
			wantErr: true,
		},
		{
			name:    "empty branch inside a group",
			pattern: `(https://github.com/NVIDIA/aicr/|)`,
			wantErr: true,
		},
		{
			// Nested in a group, so the root op is a capture rather than an
			// alternation, and the foreign branch names a repository no fixed
			// canary set can enumerate. Rejected because the pattern does not
			// begin with the repository prefix.
			name:    "nested alternation to a foreign repository",
			pattern: `(https://github.com/NVIDIA/aicr/.*|https://github.com/attacker/isolated/.*)`,
			wantErr: true,
		},
		{
			// Alternatives after the prefix stay valid: every branch is
			// already behind the pin.
			name:    "alternation after the prefix",
			pattern: `^https://github\.com/NVIDIA/aicr/\.github/workflows/(on-tag|release)\.yaml@.*`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if err := aicr.ValidateIdentityPattern(tt.pattern); (err != nil) != tt.wantErr {
				t.Errorf("ValidateIdentityPattern(%q) error = %v, wantErr %v", tt.pattern, err, tt.wantErr)
			}
		})
	}
}

// TestTrustLevels confirms the exported levels cover every value
// BundleVerifyOptions.MinTrustLevel documents.
func TestTrustLevels(t *testing.T) {
	t.Parallel()

	levels := aicr.TrustLevels()
	for _, want := range []string{"verified", "attested", "unverified", "unknown"} {
		found := false
		for _, got := range levels {
			if got == want {
				found = true
			}
		}
		if !found {
			t.Errorf("TrustLevels() = %v, missing %q", levels, want)
		}
	}
}

