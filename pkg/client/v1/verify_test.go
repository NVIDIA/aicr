// TestVerifyBundle_Guards covers every rejection that happens before any
// verification work runs.
func TestVerifyBundle_Guards(t *testing.T) {
	t.Parallel()

	client := newVerifyClient(t)
	closed := newClosedClient(t)
	dir := newChecksumBundle(t)

	tests := []struct {
		name   string
		client *aicr.Client
		ctx    context.Context //nolint:containedctx // table-driven guard inputs
		dir    string
		opts   aicr.BundleVerifyOptions
	}{
		{name: "nil client", client: nil, ctx: context.Background(), dir: dir},
		{name: "nil context", client: client, ctx: nil, dir: dir},
		{name: "empty bundle dir", client: client, ctx: context.Background(), dir: ""},
		{name: "closed client", client: closed, ctx: context.Background(), dir: dir},
		{
			name: "ignore tlog without key", client: client, ctx: context.Background(), dir: dir,
			opts: aicr.BundleVerifyOptions{IgnoreTLog: true},
		},
		{
			name: "identity pattern outside NVIDIA/aicr", client: client, ctx: context.Background(), dir: dir,
			opts: aicr.BundleVerifyOptions{CertificateIdentityRegexp: "^https://github.com/evil/repo/.*"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			_, err := tt.client.VerifyBundle(tt.ctx, tt.dir, tt.opts)
			wantInvalidRequest(t, err)
		})
	}
}

