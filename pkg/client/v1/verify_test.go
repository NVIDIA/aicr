	got, err := client.VerifyEvidence(context.Background(),
		aicr.EvidenceVerifyOptions{Input: t.TempDir()})
	// The verifier may report an unreadable bundle either as an error or as
	// an incomplete verdict; both are correct, and neither may be a silent
