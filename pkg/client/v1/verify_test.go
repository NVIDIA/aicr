// newVerifyClient returns an embedded-source Client for verification tests.
func newVerifyClient(t *testing.T) *aicr.Client {
	t.Helper()
	client, err := aicr.NewClient(aicr.WithRecipeSource(aicr.EmbeddedSource()))
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}
	t.Cleanup(func() { _ = client.Close() })
	return client
}

// newClosedClient returns a Client that has already been closed, for the
// closed-Client guard assertions.
func newClosedClient(t *testing.T) *aicr.Client {
	t.Helper()
	client, err := aicr.NewClient(aicr.WithRecipeSource(aicr.EmbeddedSource()))
	if err != nil {
		t.Fatalf("NewClient: %v", err)
	}
	if err := client.Close(); err != nil {
		t.Fatalf("Close: %v", err)
	}
	return client
}

// newChecksumBundle writes a minimal bundle whose checksums.txt is generated by
// the same code path real bundle creation uses. It carries no attestation, so
// it verifies to trust level "unverified" — the highest level it can achieve.
func newChecksumBundle(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()

	files := map[string]string{
		"recipe.yaml":              "apiVersion: v1\nkind: Recipe\n",
		"gpu-operator/values.yaml": "driver:\n  version: 570.86.16\n",
	}
	paths := make([]string, 0, len(files))
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("mkdir: %v", err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
		paths = append(paths, path)
	}
	if err := checksum.GenerateChecksums(context.Background(), dir, paths); err != nil {
		t.Fatalf("GenerateChecksums: %v", err)
	}
	return dir
}

// TestVerifyBundle_ChecksumsOnlyBundle exercises the happy path end to end: an
// unattested but checksum-valid bundle verifies, reports its trust level, and
// satisfies the default policy because the default floor is the highest level
// the bundle could reach.
func TestVerifyBundle_ChecksumsOnlyBundle(t *testing.T) {
	t.Parallel()

	client := newVerifyClient(t)
	got, err := client.VerifyBundle(context.Background(), newChecksumBundle(t), aicr.BundleVerifyOptions{})
	if err != nil {
		t.Fatalf("VerifyBundle: %v", err)
	}
	if got.Report == nil {
		t.Fatal("Report is nil on a successful verification")
	}
	if !got.Report.ChecksumsPassed {
		t.Errorf("ChecksumsPassed = false, want true (errors: %v)", got.Report.Errors)
	}
	if got.Report.ChecksumFiles != 2 {
		t.Errorf("ChecksumFiles = %d, want 2", got.Report.ChecksumFiles)
	}
	if got.PolicyFailure != "" {
		t.Errorf("PolicyFailure = %q, want empty under the default max floor", got.PolicyFailure)
	}
}

// TestVerifyBundle_EmptyMinTrustLevelMeansMax pins the deliberate departure
// from verifier.Policy, where an empty MinTrustLevel skips the trust check.
// The facade treats empty as "max" so a caller who never considered the trust
// floor still gets a gate. Both halves matter: empty must agree with an
// explicit "max", and it must NOT behave like "no check at all".
func TestVerifyBundle_EmptyMinTrustLevelMeansMax(t *testing.T) {
	t.Parallel()

	client := newVerifyClient(t)
	dir := newChecksumBundle(t)

	implicit, err := client.VerifyBundle(context.Background(), dir, aicr.BundleVerifyOptions{})
	if err != nil {
		t.Fatalf("VerifyBundle (implicit): %v", err)
	}
	explicit, err := client.VerifyBundle(context.Background(), dir, aicr.BundleVerifyOptions{MinTrustLevel: "max"})
	if err != nil {
		t.Fatalf("VerifyBundle (explicit max): %v", err)
	}
	if implicit.PolicyFailure != explicit.PolicyFailure {
		t.Errorf("implicit PolicyFailure = %q, explicit max = %q; empty must mean max",
			implicit.PolicyFailure, explicit.PolicyFailure)
	}

	// "unknown" is the floor every bundle clears, so it is the observable
	// difference between "max" and a genuinely disabled check. Tamper the
	// bundle so its actual level drops below its max achievable: under the
	// default floor that must fail, under "unknown" it must pass.
	tampered := newChecksumBundle(t)
	if writeErr := os.WriteFile(filepath.Join(tampered, "recipe.yaml"), []byte("tampered\n"), 0o600); writeErr != nil {
		t.Fatalf("tamper: %v", writeErr)
	}

	strict, err := client.VerifyBundle(context.Background(), tampered, aicr.BundleVerifyOptions{})
	if err != nil {
		t.Fatalf("VerifyBundle (tampered, default floor): %v", err)
	}
	if strict.PolicyFailure == "" && len(strict.Report.Errors) == 0 {
		t.Error("tampered bundle passed under the default floor; empty MinTrustLevel is not gating")
	}

	relaxed, err := client.VerifyBundle(context.Background(), tampered, aicr.BundleVerifyOptions{MinTrustLevel: "unknown"})
	if err != nil {
		t.Fatalf("VerifyBundle (tampered, unknown floor): %v", err)
	}
	if relaxed.PolicyFailure != "" {
		t.Errorf("PolicyFailure = %q, want empty: every bundle clears the unknown floor", relaxed.PolicyFailure)
	}
}

// TestVerifyBundle_PolicyFailureIsData locks in that an unmet policy is
// reported through the returned value rather than as an error, so a caller can
// still render the full report explaining why the bundle fell short.
func TestVerifyBundle_PolicyFailureIsData(t *testing.T) {
	t.Parallel()

	client := newVerifyClient(t)
	got, err := client.VerifyBundle(context.Background(), newChecksumBundle(t),
		aicr.BundleVerifyOptions{MinTrustLevel: "verified"})
	if err != nil {
		t.Fatalf("VerifyBundle returned an error for a policy failure; want the failure as data: %v", err)
	}
	if got.PolicyFailure == "" {
		t.Fatal("PolicyFailure is empty; an unattested bundle cannot meet the verified floor")
	}
	if got.Report == nil {
		t.Fatal("Report is nil; the report must survive a policy failure")
	}
	if !strings.Contains(got.PolicyFailure, "verified") {
		t.Errorf("PolicyFailure = %q, want it to name the required level", got.PolicyFailure)
	}
}

