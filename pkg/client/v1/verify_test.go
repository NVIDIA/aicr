// TestRecipeDigest_IsDeterministicHex verifies the digest is produced against
// the Client's own catalog and is stable across calls — the property a CI
// drift gate depends on.
func TestRecipeDigest_IsDeterministicHex(t *testing.T) {
	t.Parallel()

	path := filepath.Join(t.TempDir(), "recipe.yaml")
	if err := os.WriteFile(path, []byte("kind: RecipeResult\napiVersion: aicr.run/v1alpha2\n"), 0o600); err != nil {
		t.Fatalf("write recipe: %v", err)
	}

	client := newVerifyClient(t)
	first, err := client.RecipeDigest(context.Background(), aicr.RecipeDigestOptions{Path: path})
	if err != nil {
		t.Fatalf("RecipeDigest: %v", err)
	}
	if !regexp.MustCompile(`^[0-9a-f]{64}$`).MatchString(first) {
		t.Fatalf("RecipeDigest = %q, want lowercase hex sha256", first)
	}
	second, err := client.RecipeDigest(context.Background(), aicr.RecipeDigestOptions{Path: path})
	if err != nil {
		t.Fatalf("RecipeDigest (repeat): %v", err)
	}
	if first != second {
		t.Errorf("digest is not deterministic: %q then %q", first, second)
	}
}

