//go:build unix

package cli

import (
	"io/fs"
	"syscall"
)

// onOtherDevice reports whether a and b live on different devices. A file on
// a different device from its own parent directory is a mount point.
func onOtherDevice(a, b fs.FileInfo) bool {
	sa, okA := a.Sys().(*syscall.Stat_t)
	sb, okB := b.Sys().(*syscall.Stat_t)
	return okA && okB && sa.Dev != sb.Dev
}
